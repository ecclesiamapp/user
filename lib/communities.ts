export function getCommunitySlug(c: Community): string {
  if (c.slug) return c.slug;
  if (c.is_headquarters) return 'catedral-matriz';
  const name = c.name.toLowerCase();
  if (name.includes('perpétuo') || name.includes('perpetuo')) return 'perpetuo-socorro';
  if (name.includes('família') || name.includes('familia')) return 'sagrada-familia';
  if (name.includes('francisco')) return 'sao-francisco-de-assis';
  if (name.includes('pedro')) return 'sao-pedro';
  if (name.includes('guadalupe')) return 'nossa-senhora-de-guadalupe';
  if (name.includes('luzia')) return 'santa-luzia';
  if (name.includes('penha')) return 'nossa-senhora-da-penha';
  if (name.includes('expedito')) return 'santo-expedito';
  if (name.includes('bento')) return 'sao-bento';
  if (name.includes('lucas')) return 'sao-lucas';
  if (name.includes('rita')) return 'santa-rita-brisa-do-vale';
  return 'catedral-matriz';
}
